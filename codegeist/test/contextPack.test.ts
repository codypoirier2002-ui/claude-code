import { describe, expect, it } from 'vitest';
import { buildContextPack } from '../src/core/contextPack';
import { rankPeople } from '../src/core/people';
import { evaluateReadiness } from '../src/core/readiness';
import type { GraphContext, IssueFacts } from '../src/core/types';
import { facts, graphContext } from './fixtures';

function pack(input: IssueFacts, graph: GraphContext | null, maxChars?: number): string {
  const readiness = evaluateReadiness(input, graph);
  return buildContextPack(input, readiness, graph, rankPeople(input, graph), {
    generatedAt: '2026-11-11',
    ...(maxChars ? { maxChars } : {}),
  });
}

describe('buildContextPack', () => {
  it('includes every section a newcomer needs', () => {
    const graph = graphContext({
      note: '3 of 5 sources returned context.',
      goals: [{ name: 'Pass the SOC 2 audit', url: 'https://home.example/goal/1', dueDate: '2026-12-31T00:00:00Z' }],
      pullRequests: [{ title: 'Add CSV export', status: 'OPEN', url: 'https://git.example/pr/7' }],
      teams: [{ name: 'Compliance squad' }],
    });
    const result = pack(
      facts({
        comments: [{ author: { name: 'Ben Ode' }, created: '2026-11-02T09:00:00Z', text: 'Use ISO dates.' }],
        links: [{ key: 'KAN-3', summary: 'Audit table', statusName: 'Done', statusCategory: 'done', relation: 'is blocked by', isBlocker: true }],
      }),
      graph,
    );
    expect(result.startsWith('# KAN-12 · Let admins export audit logs as CSV')).toBe(true);
    for (const section of [
      '## Readiness:',
      '## Why it matters',
      '## Description',
      '## Linked work',
      '## Linked docs',
      '## Code',
      '## Recent discussion (newest first)',
      '## People to ask',
    ]) {
      expect(result).toContain(section);
    }
    expect(result).toContain('Part of Epic KAN-1 "Compliance reporting" (In Progress)');
    expect(result).toContain('Goal: [Pass the SOC 2 audit](https://home.example/goal/1), due 2026-12-31');
    expect(result).toContain('Owning team: Compliance squad');
    expect(result).toContain('is blocked by KAN-3 "Audit table" · Done');
    expect(result).toContain('[Audit log export spec](https://example.atlassian.net/wiki/spaces/ENG/pages/98765/Audit+log+export+spec)');
    expect(result).toContain('[Add CSV export](https://git.example/pr/7) · OPEN');
    expect(result).toContain('2026-11-02 · Ben Ode: "Use ISO dates."');
    expect(result).toContain('1. Ana Silva: Reported this work item');
    expect(result).toContain('Generated by Groundwork on 2026-11-11');
    expect(result).toContain('Teamwork Graph: 3 of 5 sources returned context.');
  });

  it('lists gaps with fixes and summarizes passed checks', () => {
    const result = pack(facts({ docs: [], storyPoints: undefined }), null);
    expect(result).toContain('⚠️ **Reference material:** No spec, design or doc is linked. Fix: Link the Confluence page');
    expect(result).toContain('Passed: Clear title, Enough detail, Done is defined');
  });

  it('flags open blockers inline', () => {
    const result = pack(
      facts({
        links: [{ key: 'KAN-3', summary: 'Audit table', statusName: 'To Do', statusCategory: 'new', relation: 'is blocked by', isBlocker: true }],
      }),
      null,
    );
    expect(result).toContain('## Readiness: ');
    expect(result).toContain('· Blocked');
    expect(result).toContain('KAN-3 "Audit table" · To Do **(open blocker)**');
  });

  it('omits code and discussion sections when there is nothing to show', () => {
    const result = pack(facts({ commentsLoaded: false }), null);
    expect(result).not.toContain('## Code');
    expect(result).not.toContain('## Recent discussion');
    expect(result).not.toContain('Teamwork Graph:');
  });

  it('stays within the character budget by trimming the description first', () => {
    const long = 'word '.repeat(4000);
    const result = pack(facts({ descriptionMarkdown: long, descriptionText: long }), null, 3000);
    expect(result.length).toBeLessThanOrEqual(3000);
    expect(result).toContain('## People to ask');
    expect(result).toContain('## Description');
  });

  it('hard-truncates when even the trimmed pack is too long', () => {
    const result = pack(facts(), null, 400);
    expect(result.length).toBeLessThanOrEqual(400);
    expect(result).toContain('(Context pack truncated to 400 characters.)');
  });

  it('is deterministic', () => {
    expect(pack(facts(), null)).toBe(pack(facts(), null));
  });
});
